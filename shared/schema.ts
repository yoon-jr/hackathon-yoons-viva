import { sql } from "drizzle-orm";
import { pgTable, text, varchar, timestamp } from "drizzle-orm/pg-core";
import { createInsertSchema } from "drizzle-zod";
import { z } from "zod";

// Marketing project data model
export const projects = pgTable("projects", {
  id: varchar("id").primaryKey().default(sql`gen_random_uuid()`),
  productName: text("product_name").notNull(),
  targetAge: text("target_age").notNull(), // "알파세대", "Z세대", "밀레니얼세대", "X세대"
  marketingSeason: text("marketing_season").notNull(), // "수능시즌", "여름", "연말"
  currentStatus: text("current_status").notNull(), // "성공", "실패", "비바이럴"
  conversationStage: text("conversation_stage").notNull().default("greeting"), // "greeting", "diagnosis", "candidates", "detailed"
  createdAt: timestamp("created_at").defaultNow(),
});

// Chat messages for conversational AI
export const messages = pgTable("messages", {
  id: varchar("id").primaryKey().default(sql`gen_random_uuid()`),
  projectId: varchar("project_id").notNull().references(() => projects.id),
  role: text("role").notNull(), // "user", "assistant", or "system"
  content: text("content").notNull(),
  metadata: text("metadata"), // JSON string for additional data (e.g., {type: "candidates", selectedStrategy: "콜라보"})
  createdAt: timestamp("created_at").defaultNow(),
});

// Marketing strategies generated by AI
export const strategies = pgTable("strategies", {
  id: varchar("id").primaryKey().default(sql`gen_random_uuid()`),
  projectId: varchar("project_id").notNull().references(() => projects.id),
  type: text("type").notNull(), // "콜라보", "네이밍", "캠페인", "시즌마케팅"
  title: text("title").notNull(),
  description: text("description").notNull(),
  imageUrl: text("image_url"), // DALL-E generated image URL
  details: text("details").notNull(), // JSON string with implementation steps
  hashtags: text("hashtags").notNull(), // Comma-separated hashtags
  createdAt: timestamp("created_at").defaultNow(),
});

// Schema validators
export const insertProjectSchema = createInsertSchema(projects).omit({
  id: true,
  createdAt: true,
});

export const insertMessageSchema = createInsertSchema(messages).omit({
  id: true,
  createdAt: true,
});

export const insertStrategySchema = createInsertSchema(strategies).omit({
  id: true,
  createdAt: true,
});

// TypeScript types
export type Project = typeof projects.$inferSelect;
export type InsertProject = z.infer<typeof insertProjectSchema>;

export type Message = typeof messages.$inferSelect;
export type InsertMessage = z.infer<typeof insertMessageSchema>;

export type Strategy = typeof strategies.$inferSelect;
export type InsertStrategy = z.infer<typeof insertStrategySchema>;

// Food sales data for market insights
export const productSales = pgTable("product_sales", {
  id: varchar("id").primaryKey().default(sql`gen_random_uuid()`),
  productName: text("product_name").notNull(),
  category: text("category").notNull(), // "초코", "사탕", "스낵", "젤리", "과자"
  brand: text("brand"),
  monthlySales: text("monthly_sales").notNull(), // Sales volume as string (e.g., "1.2만개")
  trendScore: text("trend_score").notNull(), // "상승", "하락", "유지"
  storeChain: text("store_chain"), // "CU", "GS25", "세븐일레븐", "이마트24"
  rank: text("rank"), // Popularity rank (e.g., "1위", "2위")
  recordedAt: timestamp("recorded_at").defaultNow(),
});

export const insertProductSalesSchema = createInsertSchema(productSales).omit({
  id: true,
  recordedAt: true,
});

export type ProductSales = typeof productSales.$inferSelect;
export type InsertProductSales = z.infer<typeof insertProductSalesSchema>;

// Company data model for enterprise sales analytics
export const brands = pgTable("brands", {
  id: varchar("id").primaryKey().default(sql`gen_random_uuid()`),
  name: text("name").notNull().unique(),
  description: text("description"),
  createdAt: timestamp("created_at").defaultNow(),
});

export const products = pgTable("products", {
  id: varchar("id").primaryKey().default(sql`gen_random_uuid()`),
  name: text("name").notNull(),
  brandId: varchar("brand_id").references(() => brands.id),
  brandName: text("brand_name"), // Denormalized for quick access
  category: text("category"), // Product category
  description: text("description"), // For future AI enrichment
  createdAt: timestamp("created_at").defaultNow(),
});

export const annualSales = pgTable("annual_sales", {
  id: varchar("id").primaryKey().default(sql`gen_random_uuid()`),
  productId: varchar("product_id").notNull().references(() => products.id),
  year: text("year").notNull(), // "2020", "2021", etc.
  sales: text("sales").notNull(), // Sales amount as string to preserve format
  salesNumeric: text("sales_numeric"), // Numeric value for calculations
  createdAt: timestamp("created_at").defaultNow(),
});

// Schema validators
export const insertBrandSchema = createInsertSchema(brands).omit({
  id: true,
  createdAt: true,
});

export const insertProductSchema = createInsertSchema(products).omit({
  id: true,
  createdAt: true,
});

export const insertAnnualSalesSchema = createInsertSchema(annualSales).omit({
  id: true,
  createdAt: true,
});

// TypeScript types
export type Brand = typeof brands.$inferSelect;
export type InsertBrand = z.infer<typeof insertBrandSchema>;

export type Product = typeof products.$inferSelect;
export type InsertProduct = z.infer<typeof insertProductSchema>;

export type AnnualSales = typeof annualSales.$inferSelect;
export type InsertAnnualSales = z.infer<typeof insertAnnualSalesSchema>;

// Frontend-specific types
export type AgeGroup = "알파세대" | "Z세대" | "밀레니얼세대" | "X세대";
export type MarketingSeason = "수능시즌" | "여름" | "연말" | "명절" | "기타";
export type ProductStatus = "성공" | "실패" | "비바이럴";
export type StrategyType = "콜라보" | "네이밍" | "캠페인" | "시즌마케팅" | "시즌" | "굿즈";
export type TrendScore = "상승" | "하락" | "유지";
export type ConversationStage = "greeting" | "diagnosis" | "candidates" | "detailed";
